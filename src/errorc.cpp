#include <errorc.h>

/***************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************
 * Global objects and variables
 **************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************/

uint8_t errorc = 0;

/***************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************
 * Functions
 **************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************/

/**********************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************//**
 * @brief Prints to the screen the error present in `errorc`.
 *
 * @param func The name of the function where the error is being printed (for debug purposes).
 * 
 * @return none
 *
 **************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************/
void 
printError( const char * func ){
  char buf[BUF_SIZE];

  switch( errorc ){
    case OUT_OF_BOUNDS:
      (void) snprintf( buf, BUF_SIZE, "[ERROR] Out of bounds in %s\n", func );
      break;
    
    case NOT_ENOUGH_SPACE:
      (void) snprintf( buf, BUF_SIZE, "[ERROR] Not enough space in memory in %s\n", func );
      break;

    case OVERFLOW:
      (void) snprintf( buf, BUF_SIZE, "[ERROR] Overflow in %s\n", func );
      break;

    case INVALID_OPERATION:
      (void) snprintf( buf, BUF_SIZE, "[ERROR] Invalid operation in %s\n", func );
      break;

    case UNKOWN:
      (void) snprintf( buf, BUF_SIZE, "[ERROR] Unkown error in %s\n", func );
      break;

    case NO_CARD:
      (void) snprintf( buf, BUF_SIZE, "[WARN] No card ... \n" );
      break;
    
    default:
      return;
  }

  uart0.write( buf, strlen(buf) );
}

